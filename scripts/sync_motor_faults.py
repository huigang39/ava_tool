"""Generate native diagnostic tables from FocDriver's source-validated catalog."""
import argparse
import importlib.util
import json
from pathlib import Path
import re
import sys


def definition_tokens(content: str) -> list[tuple[str, str]]:
    """Compare generated C++ definitions without depending on clang-format layout."""
    pattern = re.compile(
        r'(?P<comment>//[^\n]*|/\*[\s\S]*?\*/)'
        r'|(?P<string>"(?:\\.|[^"\\])*")'
        r'|(?P<token>[A-Za-z_][A-Za-z_0-9]*|[0-9][A-Za-z_0-9.]*'
        r'|<=>|>>=|<<=|->\*|\.\.\.|::|->|\.\*|\+\+|--|<<|>>'
        r'|<=|>=|==|!=|&&|\|\||[+*/%&|^!=-]=|##|[^\s])'
    )
    result = []
    for match in pattern.finditer(content):
        kind = match.lastgroup
        if kind == "comment":
            continue
        value = match[0]
        if kind == "string":
            # The generator emits JSON-escaped strings. clang-format may split
            # them into adjacent C++ literals without changing their value.
            value = json.loads(value)
            if result and result[-1][0] == "string":
                result[-1] = (kind, result[-1][1] + value)
                continue
        result.append((kind, value))
    return result


def generate(root: Path) -> str:
    # Build in memory from current firmware sources; never modify the firmware checkout.
    path = root / "tools/safety/safety_generate.py"
    spec = importlib.util.spec_from_file_location("foc_safety_generate", path)
    module = importlib.util.module_from_spec(spec)
    sys.dont_write_bytecode = True
    spec.loader.exec_module(module)
    catalog = module.build_catalog(root)
    if catalog["schema_version"] != 1:
        raise ValueError("Unsupported FocDriver diagnostic catalog schema")
    quote = lambda value: json.dumps(value, ensure_ascii=False)
    lines = ["// Generated by scripts/sync_motor_faults.py; do not edit",
             "// Source: FocDriver/tools/safety/safety_generate.py + current firmware sources",
             "#pragma once", "#include <cstddef>", "namespace motor_faults {",
             "enum class Mode { Bits, Enum, Predrv };",
             "struct Detail { unsigned val; const char *symbol, *zh, *cause, *action, *clear, *sources; };",
             "struct Page { const char *id, *title, *kind, *note, *source, *field; Mode mode; const Detail *entries; size_t count; };",
             "struct Definition { unsigned page, bit; const char *symbol, *zh; const Detail *detail; };",
             f"inline constexpr char catalogId[] = {quote(catalog['catalog_id'])};",
             f"inline constexpr char catalogDescription[] = {quote(catalog['description'])};"]
    pages, wire = [], []
    for index, (name, page) in enumerate(catalog["pages"].items()):
        mode = {"bits": "Bits", "enum": "Enum", "predrv": "Predrv"}[page["mode"]]
        entries = page["entries"]
        if entries:
            lines.append(f"inline constexpr Detail details{index}[] = {{")
            seen = set()
            for offset, entry in enumerate(entries):
                value = entry["value" if mode == "Enum" else "bit"]
                if value in seen or value < 0 or (mode != "Enum" and value > 31):
                    raise ValueError(f"Invalid or duplicate value in {name}: {value}")
                seen.add(value)
                sources = ", ".join(f"{s['page']}.{s['name']} (bit{s['bit']})" for s in entry.get("sources", []))
                strings = [entry.get(key, "") for key in ("name", "title", "cause", "action", "clear")] + [sources]
                lines.append("    {" + str(value) + ", " + ", ".join(map(quote, strings)) + "},")
                if name.startswith("ext"):
                    wire.append(f"    {{{int(name[3:])-1}, {value}, {quote(entry['name'])}, {quote(entry['title'])}, &details{index}[{offset}]}},")
            lines.append("};")
        strings = [name, page["title"], page["kind"], page.get("note", ""), page["source"], page.get("field", page.get("symbol", ""))]
        pages.append("    {" + ", ".join(map(quote, strings)) + f", Mode::{mode}, " + (f"details{index}" if entries else "nullptr") + f", {len(entries)}}},")
    lines += ["inline constexpr Page pages[] = {", *pages, "};", "inline constexpr Definition definitions[] = {", *wire, "};", "} // namespace motor_faults", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("foc_driver", type=Path)
    parser.add_argument("--check", action="store_true", help="Check the bundled tables without changing files")
    args = parser.parse_args()
    output = Path(__file__).resolve().parents[1] / "src/core/motor_fault_definitions.hpp"
    content = generate(args.foc_driver)
    if args.check:
        if definition_tokens(output.read_text(encoding="utf-8")) != definition_tokens(content):
            parser.error("Bundled tables differ from current FocDriver sources; run synchronization")
        print("FocDriver diagnostic tables are current")
    else:
        output.write_text(content, encoding="utf-8")
        print(f"Updated {output}")
